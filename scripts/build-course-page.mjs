// Turns the course template and logo into a module the app can import (so the page works on
// Netlify without reading files at run time). Run after editing src/content/course/template.html
// or logo.txt: `node scripts/build-course-page.mjs`. course.test.ts fails if you forget.
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/content/course/", import.meta.url);
const template = readFileSync(new URL("template.html", dir), "utf8");
const logo = readFileSync(new URL("logo.txt", dir), "utf8").trim();
writeFileSync(
  new URL("page.generated.ts", dir),
  `// Generated by scripts/build-course-page.mjs from template.html and logo.txt. Don't edit by hand.\nexport const COURSE_TEMPLATE = ${JSON.stringify(template)};\nexport const COURSE_LOGO = ${JSON.stringify(logo)};\n`,
);
